<h2>References and disclaimer</h2>

<p>
  The process is based on Presidential Decree No. 702, the government’s eligible
  country order, the Ministry of Internal Affairs regulations for TRPs and
  migration registration, and the Ministry of Health examination procedure.
  Immigration regulations change frequently. Confirm requirements, fees, and
  document validity with an official Migration Directorate or qualified
  immigration professional.
</p>
