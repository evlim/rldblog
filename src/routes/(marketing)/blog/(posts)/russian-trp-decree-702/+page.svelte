<p class="lead">
  A practical guide to applying for a temporary residence permit in Russia under
  Presidential Decree 702.
</p>

<p>
  I obtained a Temporary Residence Permit (TRP) in Russia under Presidential
  Decree 702. This guide is based on that experience and on the official
  requirements available when it was updated. It is intended to make a complex
  process easier to plan; it is not legal advice.
</p>

<h2>What Decree 702 changes</h2>

<p>
  A TRP (разрешение на временное проживание, РВП) allows a foreign citizen to
  live and work, or start a business, in the Russian federal subject that grants
  it. The permit is valid for three years. Decree 702 lets eligible citizens and
  permanent residents of listed countries apply outside the quota and without
  exams in Russian language, history, or legislation.
</p>

<p>
  Eligibility depends on the country list approved by the Russian government and
  on sharing traditional Russian spiritual and moral values. Check the current
  list in the <a href="/tools#eligibility" class="link">eligibility tool</a>
  before arranging documents.
</p>

<h2>Plan the application in order</h2>

<ol>
  <li>
    <h3>Obtain and legalize your criminal record certificate</h3>
    <p>
      Applicants aged 14 and over need a certificate issued by the competent
      authority in their country. There is no published rule that the record
      must be clean. The certificate is generally valid for three months, so
      start this step first and confirm the current validity period with the
      Migration Directorate.
    </p>
    <p>
      The <a href="/tools#criminal-record" class="link">criminal record tool</a>
      contains common certificate names by country. It is a reference, not an official
      list of acceptable documents.
    </p>
  </li>
  <li>
    <h3>Prepare supporting civil documents</h3>
    <p>
      Gather birth certificates for accompanying minors and documents proving
      name changes, such as marriage or divorce certificates. Apostille or
      legalize foreign public documents as required. Taiwan and Micronesia
      require different legalization routes because they are not parties to the
      Apostille Convention.
    </p>
  </li>
  <li>
    <h3>Apply for a visa and enter Russia</h3>
    <p>
      The “shared values visa” is a single-entry private visa valid for up to 90
      days. Other valid Russian visas may also work, but check the purpose and
      validity before relying on one. A border officer issues the migration card
      on entry.
    </p>
  </li>
  <li>
    <h3>Complete migration registration</h3>
    <p>
      Registration of place of stay must normally be completed within seven
      business days. A hotel should arrange it. At a private residence, the
      property owner submits the notification at an MFC (“My Documents”) or a
      Migration Directorate. Keep the tear-off slip as proof.
    </p>
  </li>
  <li>
    <h3>Translate and notarize documents</h3>
    <p>
      Foreign documents for the TRP application must be translated into Russian
      and notarized in Russia. A translation bureau can usually arrange both
      services. Prepare translations of every passport page, the criminal record
      certificate, and any applicable birth, marriage, or divorce certificates.
    </p>
  </li>
  <li>
    <h3>Complete the medical examination</h3>
    <p>
      An authorized medical organization in the region where you will apply must
      issue certificates covering prohibited substances, dangerous infectious
      diseases, and HIV. Bring your passport, visa, migration card, migration
      registration, and a notarized passport translation. Results often take
      five business days, and confirmatory testing can take longer.
    </p>
  </li>
  <li>
    <h3>Complete the form and pay the state duty</h3>
    <p>
      Complete the official TRP application, prepare two 3.5 × 4.5 cm
      photographs (five for a stateless applicant), and keep the payment
      receipt. The state duty was 1,920 rubles; it increased to 15,000 rubles
      after 26 July 2026. Confirm the current amount before payment.
    </p>
  </li>
  <li>
    <h3>Submit the application</h3>
    <p>
      Make two copies of the documents and submit the application in person at
      the appropriate Multifunctional Migration Center or Migration Directorate.
      Bring your passport, visa, notarized translations, migration card,
      registration proof, criminal record and medical certificates, residence
      proof where applicable, name-change or minor documents where applicable,
      photographs, application form, and duty receipt.
    </p>
  </li>
  <li>
    <h3>Collect the decision and permit</h3>
    <p>
      The standard processing period is four months from acceptance. You will
      receive a notification of the result and, if approved, a receipt
      explaining your rights and responsibilities. For passport holders, the TRP
      is a stamp in the passport; stateless applicants receive a separate
      document.
    </p>
  </li>
</ol>

