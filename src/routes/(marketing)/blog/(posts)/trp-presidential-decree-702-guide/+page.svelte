<h3>5. Translation and Notarization</h3>

<p>
  TRP application requires all foreign documents to be translated into Russian
  and notarized by notary in Russia <sup>[4]</sup>.
</p>

<p>
  The translation and notarization can be completed in one of the following ways <sup
    >[11]</sup
  >:
</p>

<p class="article-condition">
  <span class="article-emphasis"
    >if the notary is proficient in the relevant languages: the notary certifies
    the accuracy of a translation from one language to another</span
  >
</p>

<p class="article-condition">
  <span class="article-emphasis"
    >if the notary is not proficient in the relevant languages: the notary
    certifies the authenticity of a translator's signature</span
  >
</p>

<p>
  According to recent regulations <sup>[12]</sup>, you likely cannot act as your
  own translator unless the notary is proficient in your language. The easiest
  method is to use a Russian translation bureau that handles both translation
  and notarization.
</p>

<p>Documents requiring translation:</p>

<ul class="article-list">
  <li><span class="article-emphasis">Passport (all pages)</span></li>
  <li><span class="article-emphasis">Criminal record certificate</span></li>
  <li>Birth certificate (if applicable)</li>
  <li>Marriage/Divorce certificate (if applicable)</li>
</ul>

<p>
  I recommend getting two sets of notarized passport translations: one with all
  pages (for the TRP application) and another with only the biometric page (for
  banking, MFC services, etc.).
</p>

<h3>6. Medical Examination</h3>

<p>
  A medical examination is required for the TRP application and to comply with
  federal law, which mandates it within 90 days of entry (or 30 days if engaging
  in labor activities) <sup>[13]</sup>. You fulfill both requirements with one
  examination.
</p>

<p>Three medical certificates are required <sup>[4, 14]</sup>:</p>

<ul class="article-list">
  <li>
    <span class="article-emphasis"
      >if 13 years old or above: Medical report of absence of drugs and
      psychotropic substances in the body</span
    >
    (in Russian: Медицинское заключение об отсутствии факта употребления иностранным
    гражданином или лицом без гражданства наркотических средств или психотропных
    веществ без назначения врача либо новых потенциально опасных психоактивных веществ
    и их метаболитов)
  </li>
  <li>
    <span class="article-emphasis"
      >Medical report on the presence (absence) of infectious diseases that pose
      a danger to others</span
    >
    (in Russian: Медицинское заключение наличии (отсутствии) инфекционных заболеваний,
    представляющих опасность для окружающих)
  </li>
  <li>
    <span class="article-emphasis"
      >Certificate of absence of human immunodeficiency virus (HIV) infection</span
    >
    (in Russian: Сертификат об отсутствии вируса иммунодефицита человека (ВИЧ-инфекции))
  </li>
</ul>

<p>
  You must undergo the examination at a medical organization in your chosen
  Russian region authorized to issue these documents <sup>[14]</sup>.
</p>

<p>
  According to the Order of the Ministry of Health of the Russian Federation,
  you will need your passport, visa, and migration card <sup>[14]</sup>.
  Although the order does not list them, several semi official sources,
  including universities, also recommend bringing your migration registration
  and a notarized translation of the passport. I suggest bringing those
  documents as well, just in case.
</p>

<p>
  Results are typically ready in <b>5 business days</b>. If a urine test
  indicates substances, a confirmatory test is performed, extending the total
  time to a maximum of 18 business days <sup>[14]</sup>.
</p>

