<h3>4. Migration Registration</h3>

<p>
  Registration of place of stay must be completed within 7 business days of
  arrival <sup>[8]</sup>. Please note that this process differs from
  registration of place of residence. For simplicity, we will refer to
  registration of place of stay as "migration registration."
</p>

<ul class="article-list">
  <li>
    <span class="article-emphasis"
