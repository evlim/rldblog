<h3>3. Migration Card</h3>

<p>
  The migration card is proof of your legal entry into Russia. You receive it
  from a border control officer when entering the country. Fig. 5 shows my
  migration card. Although official government resolutions state that the
  foreign citizen must fill it out <sup>[7]</sup>, in my experience, the officer
  always types and prints it. This appears to be a standard practice implemented
  after the latest amendments.
</p>

