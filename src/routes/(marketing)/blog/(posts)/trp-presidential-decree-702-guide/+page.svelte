<h3>1. Criminal Record Certificate (Apostilled or Legalized)</h3>

<p>
  This document, issued by the competent authority in your country of
  citizenship, confirms your criminal record status. There is no official
  requirement stating you need a clean record <sup>[4]</sup>. While the Russian
  government has not published an official list of acceptable documents by
  country, I have compiled a reference list of criminal record check names. You
  can use the
  <a href="/tools#criminal-record" class="link"
    >criminal record certificate tool</a
  > to find common names by country.
</p>

<p>
  This certificate is required for applicants aged 14 and over and is valid for
  3 months from its issuance date <sup>[4]</sup>. It has the shortest validity
  period of all required documents and is often a bottleneck because it requires
  apostille or legalization. Therefore, you should start this process first.
</p>

<p>
  If you are bringing minors, obtain their birth certificates. If you have
  changed your name, gather the relevant documents (e.g., marriage or divorce
  certificates). These documents do not expire but will also need apostille or
  legalization.
</p>

<p>
  After obtaining the documents, get them apostilled, unless you are from Taiwan
  or Micronesia—the only two eligible states not party to the Apostille
  Convention <sup>[5]</sup>. I recommend applying for the "shared values visa"
  at a Russian embassy or consulate concurrently while your documents are being
  apostilled.
</p>

<p>
  All non-Russian documents must be translated into Russian and notarized. While
  you can have translations notarized at a Russian consulate, I recommend
  waiting until you arrive in Russia. Translation bureaus there can handle both
  translation and notarization quickly (often within one business day) and
  usually at a lower cost.
</p>

<p>Special Country Notes:</p>

<ul>
  <li>
    Belgium: Adult applicants also need an apostilled birth certificate. In case
    of name discrepancies across documents, you may need a certificate of
    identity confirmation from the Embassy of Belgium in Russia <sup>[6]</sup>.
  </li>
</ul>

<ul>
  <li>
    Switzerland: Adult applicants also need an apostilled birth certificate and
    a birth certificate confirmation issued by the Embassy of Switzerland in
    Russia <sup>[6]</sup>.
  </li>
</ul>

<ul>
  <li>
    Taiwan (China): Get documents legalized at the Moscow-Taipei Coordination
    Commission on Economic and Cultural Cooperation (MTC).
  </li>
</ul>

<ul>
  <li>
    Micronesia: There is no Russian embassy in Micronesia. The Russian Embassy
    in Manila, Philippines, handles these duties. Documents likely need internal
    Micronesian authentication followed by legalization at the Russian Embassy
    in the Philippines. Confirm this directly with the embassy.
  </li>
</ul>

<h3>2. Passport and Visa</h3>

<p>
  The visa for entering Russia to obtain a TRP under Decree 702 is known as a
  "shared values visa." It is a single-entry private visa valid for up to 90
  days <sup>[3]</sup>. The 90-day period typically starts from your entry date
  into Russia, which may differ from the visa issuance date.
</p>

<p>
  I applied for my shared values visa at the MTC in Taiwan. The officer assisted
  me with the Russian-language sections of the form. Notably, I was not required
  to state my exact reasons for applying.
</p>

<p>
  I received my shared values visa, as shown in Fig. 4, which references
  Presidential Decree No. 702 in the additional information section.
</p>

