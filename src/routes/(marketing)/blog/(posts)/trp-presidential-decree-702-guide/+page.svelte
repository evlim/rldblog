<h2>Introduction</h2>

<h3>
  What is a Temporary Residence Permit (TRP) in Russia Under Presidential Decree
  702?
</h3>

<p>
  A Temporary Residence Permit (TRP; in Russian: Разрешение на временное
  проживание, РВП) allows foreign citizens to live and work without a separate
  permit, or to start a business, within the specific federal subject where the
  TRP is granted. TRPs are valid for 3 years <sup>[1]</sup>.
</p>

<p>
  Presidential Decree 702 provides humanitarian support to individuals who share
  traditional Russian spiritual and moral values. It allows eligible foreign
  citizens to apply for a TRP without being subject to a quota and without
  taking exams on Russian language, history, or legislation <sup>[2]</sup>. The
  decree was signed on August 19, 2024, and applications became possible on
  September 17, 2024, when the official list of eligible states and territories
  was published <sup>[3]</sup>.
</p>

<h3>
  Who is Eligible to Apply for a TRP in Russia Under Presidential Decree 702?
</h3>

<p>
  Citizens or stateless persons with permanent residency from a select list of
  countries who share traditional Russian spiritual and moral values are
  eligible. The <a href="/tools#eligibility" class="link"
    >Decree 702 eligibility tool</a
  >
  contains the current reference list of eligible states and territories according
  to the governmental order <sup>[3]</sup>.
</p>

